function toggleFavorite(id, title) {

    const index =
        favoritesList.findIndex(
            item => item.id === id
        );

    if (index >= 0) {

        favoritesList.splice(
            index,
            1
        );

    } else {

        favoritesList.push({
            id,
            title
        });
    }

    saveData();

    closeModal();
}


