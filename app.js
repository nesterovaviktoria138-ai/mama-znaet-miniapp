function openSection(sectionName) {    
    const data = sections[sectionName];

    if (!data) {
        return;
    }

    screen.innerHTML = `

        <button
            class="back-button"
            onclick="location.reload()"
        >
            ← На главную
        </button>


        <div class="content-page">

            <span class="age-badge">
                МАМА ЗНАЕТ
            </span>

            <h1>
                ${data.icon} ${data.title}
            </h1>

            <p>
                ${data.description}
            </p>


            <div class="checklist">

                ${data.items.map((item, index) => `

                    <button
                        class="check-item"
                        onclick="openArticle(
                            '${sectionName}',
                            ${index}
                        )"
                    >

                        <span>
                            ${item}
                        </span>

                        <strong>
                            ›
                        </strong>

                    </button>

                `).join("")}

            </div>

        </div>
    `;

    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });
}


