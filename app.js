function saveLog(icon, type) {

    const input =
        document.getElementById(
            "logText"
        );

    logs.push({

        icon,

        type,

        text:
            input.value.trim()
            || "Без заметки",

        time:
            new Date()
            .toLocaleString("ru-RU")

    });

    saveData();

    closeModal();

    diary();
}


function renderLogs() {

    if (!logs.length) {

        return `
            <div class="info-box">
                Пока нет записей.
            </div>
        `;
    }


    return logs
        .slice()
        .reverse()
        .map(item => `

            <div class="info-box">

                <strong>
                    ${item.icon}
                    ${item.type}
                </strong>

                <p>
                    ${item.text}
                </p>

                <small>
                    ${item.time}
                </small>

            </div>

        `)
        .join("");
}


