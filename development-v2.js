function getDevelopmentV2Storage() {
    try {
        return JSON.parse(
            localStorage.getItem("developmentV2Checks") || "{}"
        );
    } catch (error) {
        return {};
    }
}


function getDevelopmentV2Check(ageIndex, itemIndex) {
    const saved = getDevelopmentV2Storage();

    return Boolean(
        saved[ageIndex] &&
        saved[ageIndex][itemIndex]
    );
}


function saveDevelopmentV2Check(
    ageIndex,
    itemIndex,
    checked
) {
    const saved = getDevelopmentV2Storage();

    if (!saved[ageIndex]) {
        saved[ageIndex] = {};
    }

    saved[ageIndex][itemIndex] = Boolean(checked);

    localStorage.setItem(
        "developmentV2Checks",
        JSON.stringify(saved)
    );
}


