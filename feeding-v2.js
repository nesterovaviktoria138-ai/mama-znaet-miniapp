/* =========================================================
   ПОЛУЧАЕМ ЭТАП ПО ВОЗРАСТУ
   ========================================================= */

function getFeedingV2AgeGroup() {
    const months = getFeedingV2BabyMonths();

    if (months === null) {
        return null;
    }

    return feedingV2AgeGroups.find(
        group =>
            months >= group.min &&
            months <= group.max
    ) || feedingV2AgeGroups[feedingV2AgeGroups.length - 1];
}


/* =========================================================
   ЭКРАНИРОВАНИЕ ТЕКСТА
   ========================================================= */

function feedingV2Escape(text) {
    return String(text ?? "")
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;")
        .replace(/'/g, "&#039;");
}
