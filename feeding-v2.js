/* =========================================================
   УНИВЕРСАЛЬНЫЙ РЕНДЕР СПИСКА
   ========================================================= */

function feedingV2RenderList(items, icon = "✓") {
    if (!Array.isArray(items) || !items.length) {
        return "";
    }

    return `
        <div class="feeding-v2-list">
            ${items.map(item => `
                <div class="feeding-v2-list-item">
                    <span class="feeding-v2-list-icon">
                        ${icon}
                    </span>

                    <span>
                        ${feedingV2Escape(item)}
                    </span>
                </div>
            `).join("")}
        </div>
    `;
}


