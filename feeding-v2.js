/* ===== БЕЗОПАСНО ПОЛУЧАЕМ ЗНАЧЕНИЕ ПОЛЯ ===== */

function feedingV2GetValue(id) {
    const element = document.getElementById(id);
    return element ? element.value : "";
}


/* ===== СОБИРАЕМ ДАННЫЕ ===== */

function feedingV2CollectAnalyzerData() {

    const data = {
        type: feedingV2SelectedType,
        concern: feedingV2GetValue("feedingV2Concern")
    };


    if (data.type === "formula") {

        data.feedCount =
            feedingV2GetValue("feedingV2FeedCount");

        data.feedVolume =
            feedingV2GetValue("feedingV2FeedVolume");

        data.afterFeed =
            feedingV2GetValue("feedingV2AfterFeed");
    }


    if (data.type === "breast") {

        data.breastFrequency =
            feedingV2GetValue(
                "feedingV2BreastFrequency"
            );

        data.breastEffect =
            feedingV2GetValue(
                "feedingV2BreastEffect"
            );
    }


    if (data.type === "mixed") {

        data.mixedMain =
            feedingV2GetValue(
                "feedingV2MixedMain"
            );

        data.supplement =
            feedingV2GetValue(
                "feedingV2Supplement"
            );
    }


    return data;
}


/* ===== ПРОВЕРЯЕМ ФОРМУ ===== */

function feedingV2ValidateAnalyzer(data) {

    if (!data.concern) {
        return "Выберите, что вас беспокоит больше всего.";
    }


    if (data.type === "formula") {

        if (
            !data.feedCount ||
            !data.feedVolume ||
            !data.afterFeed
        ) {
            return "Заполните данные о кормлении смесью.";
        }


        const volume =
            Number(data.feedVolume);

        if (
            !Number.isFinite(volume) ||
            volume < 10 ||
            volume > 400
        ) {
            return "Проверьте объём одного кормления.";
        }
    }


    if (data.type === "breast") {

        if (
            !data.breastFrequency ||
            !data.breastEffect
        ) {
            return "Ответьте на вопросы о грудном вскармливании.";
        }
    }


    if (data.type === "mixed") {

        if (
            !data.mixedMain ||
            !data.supplement
        ) {
            return "Заполните данные о смешанном кормлении.";
        }
    }


    return "";
}


/* ===== ЗАПУСК ===== */

function runFeedingV2Analyzer() {

    const data =
        feedingV2CollectAnalyzerData();

    const error =
        feedingV2ValidateAnalyzer(data);

    const validation =
        document.getElementById(
            "feedingV2Validation"
        );


    if (error) {

        if (validation) {
            validation.textContent = error;
        }

        return;
    }


    if (validation) {
        validation.textContent = "";
    }


    feedingV2SaveAnalyzer(data);

    showFeedingV2Analysis(data);
}


