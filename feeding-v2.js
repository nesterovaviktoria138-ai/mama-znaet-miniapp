/* ===== СОХРАНЕНИЕ АНАЛИЗАТОРА ===== */

function feedingV2SaveAnalyzer(data) {
    try {
        localStorage.setItem(
            "feedingV2Analyzer",
            JSON.stringify(data)
        );
    } catch (error) {
        console.log(
            "Не удалось сохранить анализатор кормления",
            error
        );
    }
}


function feedingV2LoadAnalyzer() {
    try {
        return JSON.parse(
            localStorage.getItem("feedingV2Analyzer") || "null"
        );
    } catch (error) {
        return null;
    }
}


function feedingV2ClearAnalyzer() {
    localStorage.removeItem("feedingV2Analyzer");
    feedingV2SelectedType = "formula";
    openFeedingV2Analyzer();
}


/* =========================================================
   ВЫБОР ТИПА КОРМЛЕНИЯ
   ========================================================= */

function selectFeedingV2Type(type) {

    if (!feedingV2Types[type]) {
        return;
    }

    feedingV2SelectedType = type;

    document
        .querySelectorAll(".feeding-v2-analyzer-type")
        .forEach(button => {
            button.classList.toggle(
                "active",
                button.dataset.type === type
            );
        });


    const dynamic =
        document.getElementById(
            "feedingV2AnalyzerDynamic"
        );

    if (dynamic) {
        dynamic.innerHTML =
            feedingV2AnalyzerFields(type);
    }
}


